def apagar_ponto(idx):
    global caderneta_dados
    if 0 <= idx < len(caderneta_dados):
        recalcular_azimutes()
        removido = caderneta_dados[idx]
        # Quem usava este ponto como ré passa a usar o azimute que ele tinha (ré fixa), em vez de perder a referência
        dependentes = []
        for p in caderneta_dados:
            if p is not removido and p.get('re_id') == removido['id']:
                p['re_id'] = -1
                p['re_az'] = removido['az_dec']
                dependentes.append(p['ponto'])
        caderneta_dados.pop(idx)
        fechar_painel_analise()
        atualizar_opcoes_re()
        txt_nome.value = removido['ponto']
        with out_status:
            clear_output()
            print(f"Ponto '{removido['ponto']}'removido com sucesso!")
            if dependentes:
                print(f"ℹ{', '.join(dependentes)} usava(m) esse ponto como ré e agora mantém(êm) a ré fixa em Az {dec_para_gms_str(removido['az_dec'])}.")
        atualizar_tabela_tela()

