def calcular_areas_secao_transversal(distancias, cotas_terreno, cota_projeto):
    """Calcula áreas exatas de corte e aterro de uma seção transversal pelo método analítico."""
    area_corte = 0.0
    area_aterro = 0.0

    for i in range(len(distancias) - 1):
        d1, d2 = float(distancias[i]), float(distancias[i + 1])
        L = d2 - d1
        if L <= 1e-9:
            continue

        h1 = float(cotas_terreno[i]) - float(cota_projeto)
        h2 = float(cotas_terreno[i + 1]) - float(cota_projeto)

        if h1 >= 0 and h2 >= 0:
            area_corte += ((h1 + h2) / 2.0) * L
        elif h1 <= 0 and h2 <= 0:
            area_aterro += ((abs(h1) + abs(h2)) / 2.0) * L
        else:
            L1 = L * abs(h1) / (abs(h1) + abs(h2))
            L2 = L - L1
            if h1 > 0:
                area_corte += (h1 * L1) / 2.0
                area_aterro += (abs(h2) * L2) / 2.0
            else:
                area_aterro += (abs(h1) * L1) / 2.0
                area_corte += (h2 * L2) / 2.0

    return area_corte, area_aterro

def extrair_secoes_terraplenagem(df_malha, cota_projeto=None):
    """Agrupa a malha em seções transversais (perfis horizontais), calcula áreas e volumes."""
    if cota_projeto is None:
        cota_projeto = COTA_PLATO_PADRAO
    if df_malha is None or len(df_malha) < 3:
        return None

    df = df_malha.copy()
    secoes_dict = {}

    borda_sup = SECAO_BORDA_SUP_PADRAO
    nomes_borda = {normalize_point_name(n) for n in borda_sup['pontos']} if borda_sup else set()

    for _, row in df.iterrows():
        p_norm = normalize_point_name(row['Ponto'])
        y_val = float(row['Y'])
        if borda_sup and (p_norm in nomes_borda or y_val > borda_sup['y_limite']):
            chave = borda_sup['y_medio']
            nome_secao = borda_sup['nome']
        else:
            y_snap = round(y_val * 2.0) / 2.0
            if abs(y_val - y_snap) > 0.25:
                continue
            chave = y_snap
            nome_secao = ROTULOS_SECOES_Y_PADRAO.get(y_snap, f"Seção Y = {y_snap:.2f} m")

        secoes_dict.setdefault(chave, {'nome': nome_secao, 'y_ref': chave, 'pontos': []})
        if not any(abs(p['X'] - float(row['X'])) < 1e-4 for p in secoes_dict[chave]['pontos']):
            secoes_dict[chave]['pontos'].append({
                'Ponto': row['Ponto'],
                'X': float(row['X']),
                'Y': float(row['Y']),
                'Cota': float(row['Cota'])
            })

    secoes_ordenadas = []
    for chave in sorted(secoes_dict.keys()):
        sec = secoes_dict[chave]
        pts_ord = sorted(sec['pontos'], key=lambda item: item['X'])
        if len(pts_ord) < 2:
            continue
        x_min = pts_ord[0]['X']
        dists = [p['X'] - x_min for p in pts_ord]
        cotas = [p['Cota'] for p in pts_ord]
        nomes = [p['Ponto'] for p in pts_ord]
        a_corte, a_aterro = calcular_areas_secao_transversal(dists, cotas, cota_projeto)

        secoes_ordenadas.append({
            'Seção': sec['nome'],
            'Y_ref': sec['y_ref'],
            'Pontos': nomes,
            'X_coords': [p['X'] for p in pts_ord],
            'Distâncias': dists,
            'Cotas': cotas,
            'Extensão (m)': round(dists[-1], 3),
            'Área Corte (m²)': round(a_corte, 4),
            'Área Aterro (m²)': round(a_aterro, 4)
        })

    if not secoes_ordenadas:
        return None

    tabela_volumes = []
    vol_corte_total = 0.0
    vol_aterro_total = 0.0

    for i in range(len(secoes_ordenadas) - 1):
        s1 = secoes_ordenadas[i]
        s2 = secoes_ordenadas[i + 1]
        dist_entre_secoes = round(s2['Y_ref'] - s1['Y_ref'], 4)
        vc = ((s1['Área Corte (m²)'] + s2['Área Corte (m²)']) / 2.0) * dist_entre_secoes
        va = ((s1['Área Aterro (m²)'] + s2['Área Aterro (m²)']) / 2.0) * dist_entre_secoes
        vol_corte_total += vc
        vol_aterro_total += va

        tabela_volumes.append({
            'Trecho entre Seções': f"{s1['Seção'].split('(')[0]} → {s2['Seção'].split('(')[0]}",
            'Distância (m)': dist_entre_secoes,
            'Corte S1 (m²)': s1['Área Corte (m²)'],
            'Corte S2 (m²)': s2['Área Corte (m²)'],
            'Vol. Corte (m³)': round(vc, 4),
            'Aterro S1 (m²)': s1['Área Aterro (m²)'],
            'Aterro S2 (m²)': s2['Área Aterro (m²)'],
            'Vol. Aterro (m³)': round(va, 4)
        })

    return {
        'cota_projeto': float(cota_projeto),
        'secoes': secoes_ordenadas,
        'volumes': tabela_volumes,
        'vol_corte_total': round(vol_corte_total, 4),
        'vol_aterro_total': round(vol_aterro_total, 4),
        'diferenca_volumes': round(vol_aterro_total - vol_corte_total, 4)
    }

def gerar_grafico_perfil_terraplenagem(secao_obj, cota_projeto):
    """Plota um perfil transversal detalhado com hachura de corte (vermelho) e aterro (azul)."""
    plt.ioff()
    fig, ax = plt.subplots(figsize=(10.5, 4.3), dpi=100)

    dists = np.array(secao_obj['Distâncias'], dtype=float)
    cotas = np.array(secao_obj['Cotas'], dtype=float)
    nomes = secao_obj['Pontos']

    d_fine = np.linspace(dists[0], dists[-1], 400)
    z_fine = np.interp(d_fine, dists, cotas)

    ax.plot(dists, cotas, marker='o', color='#8b0000', linewidth=2.2, markersize=6, label='Terreno Natural', zorder=4)
    ax.axhline(cota_projeto, color='#1F4E78', linestyle='-', linewidth=2.0, label=f'Platô ({cota_projeto:.4f} m)', zorder=3)

    ax.fill_between(d_fine, z_fine, cota_projeto, where=(z_fine >= cota_projeto),
                    interpolate=True, color='#d9534f', alpha=0.28, label=f"Corte ({secao_obj['Área Corte (m²)']:.4f} m²)")
    ax.fill_between(d_fine, z_fine, cota_projeto, where=(z_fine <= cota_projeto),
                    interpolate=True, color='#1F4E78', alpha=0.22, label=f"Aterro ({secao_obj['Área Aterro (m²)']:.4f} m²)")

    for d_i, z_i, nm in zip(dists, cotas, nomes):
        ax.axvline(d_i, color='#7f8c8d', linestyle=':', linewidth=0.9, alpha=0.7)
        ax.annotate(f"{nm}\n{z_i:.4f}", (d_i, z_i), textcoords="offset points", xytext=(0, 8),
                    ha='center', fontsize=7.5, fontweight='bold',
                    bbox=dict(boxstyle="round,pad=0.18", fc="white", ec="#ccc", alpha=0.85))

    ax.set_xticks(dists)
    ax.set_xticklabels([f"{nm}\n({d_i:.2f}m)"for nm, d_i in zip(nomes, dists)], fontsize=8)
    ax.set_ylabel('Cota (m)', fontweight='bold', color='#1F4E78')
    ax.set_title(f"{secao_obj['Seção']} — Corte: {secao_obj['Área Corte (m²)']:.4f} m² | Aterro: {secao_obj['Área Aterro (m²)']:.4f} m²",
                 fontsize=11.5, fontweight='bold', color='#1F4E78', pad=12)
    ax.grid(True, linestyle='--', alpha=0.45)
    ax.legend(loc='upper left', fontsize=8.5, frameon=True)
    plt.tight_layout()
    return fig

