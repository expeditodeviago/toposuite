def fmt_x_ew(valor, casas):
    '''ΔX: positivo -> E (Leste), negativo -> W (Oeste).'''
    letra = "E" if valor >= 0 else "W"
    return f"{abs(valor):.{casas}f} {letra}"

def fmt_y_ns(valor, casas):
    '''ΔY: positivo -> N (Norte), negativo -> S (Sul).'''
    letra = "N" if valor >= 0 else "S"
    return f"{abs(valor):.{casas}f} {letra}"

def calcular_correcoes_inteiras_sec(erro_angular_sec, angulos_brutos_dec):
    n = len(angulos_brutos_dec)
    if n == 0:
        return []

    C_total = int(round(-erro_angular_sec))
    base_flt = C_total / n

    if C_total >= 0:
        val_menor = int(math.floor(base_flt))
        val_maior = val_menor + 1
        qtd_maior = C_total - (val_menor * n)
        qtd_menor = n - qtd_maior
    else:
        val_maior = int(math.ceil(base_flt))
        val_menor = int(math.floor(base_flt))
        qtd_maior = C_total - (n * val_menor)
        qtd_menor = n - qtd_maior

    indices_ordenados = sorted(range(n), key=lambda i: angulos_brutos_dec[i], reverse=True)
    correcoes = [val_menor] * n

    if C_total >= 0:
        for idx in range(n):
            orig_i = indices_ordenados[idx]
            if idx < qtd_maior:
                correcoes[orig_i] = val_maior
            else:
                correcoes[orig_i] = val_menor
    else:
        qtd_maior_mod = n - qtd_maior
        for idx in range(n):
            orig_i = indices_ordenados[idx]
            if idx < qtd_maior_mod:
                correcoes[orig_i] = val_menor
            else:
                correcoes[orig_i] = val_maior

    return correcoes

def formatar_descricao_correcao_angular(correcoes_sec):
    if not correcoes_sec:
        return "Nenhuma correção aplicada."
    unicos = sorted(list(set(correcoes_sec)), reverse=True)
    if len(unicos) == 1:
        sinal = "+" if unicos[0] > 0 else ""
        return f"{sinal}{unicos[0]}\"por vértice."
    else:
        partes = []
        for val in unicos:
            qtd = correcoes_sec.count(val)
            sinal = "+" if val > 0 else ""
            if val == max(unicos):
                partes.append(f"{qtd} vértice(s) com {sinal}{val}\"(maiores ângulos)")
            else:
                partes.append(f"{qtd} vértice(s) com {sinal}{val}\"(menores ângulos)")
        return " | ".join(partes)

