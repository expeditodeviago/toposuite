def _is_valid_num(val):
    return val is not None and not (isinstance(val, float) and np.isnan(val))

def calcular_caderneta(dados, cota_inicial=None):
    """Processa nivelamento simples ou composto (múltiplas estações com ré em RN ou ponto anterior)."""
    if cota_inicial is None:
        cota_inicial = COTA_INICIAL_PADRAO
    if not dados:
        return None, None, None

    resultados = []
    pontos_perfil = []
    cotas_calculadas = {}

    cota_referencia = float(cota_inicial)
    ai_atual = None
    soma_re = 0.0
    soma_vante_mudanca = 0.0
    cota_ultima_mudanca = float(cota_inicial)
    houve_mudanca = False

    for idx, linha in enumerate(dados):
        estacao = linha.get('estacao', '')
        ponto = linha.get('ponto', '')
        p_norm = normalize_point_name(ponto)
        visada_re = linha.get('re')
        vante_inter = linha.get('vante_inter')
        vante_mudanca = linha.get('vante_mudanca')
        ponto_ref_re = (linha.get('ponto_ref_re') or '').strip()

        tem_re = _is_valid_num(visada_re)
        tem_vi = _is_valid_num(vante_inter)
        tem_vm = _is_valid_num(vante_mudanca)

        if tem_re:
            if ponto_ref_re:
                ref_norm = normalize_point_name(ponto_ref_re)
                if ref_norm in cotas_calculadas:
                    cota_referencia = cotas_calculadas[ref_norm]
            elif p_norm in cotas_calculadas:
                cota_referencia = cotas_calculadas[p_norm]

            ai_atual = cota_referencia + float(visada_re)
            soma_re += float(visada_re)
            cotas_calculadas[p_norm] = cota_referencia
            cota_ponto = cota_referencia
            tipo_leitura = "Ré (Início/Mudança)"
        else:
            cota_ponto = None
            tipo_leitura = "Intermediária"

        if tem_vm and ai_atual is not None:
            cota_ponto = ai_atual - float(vante_mudanca)
            cota_referencia = cota_ponto
            cota_ultima_mudanca = cota_ponto
            soma_vante_mudanca += float(vante_mudanca)
            houve_mudanca = True
            cotas_calculadas[p_norm] = cota_ponto
            tipo_leitura = "Vante de Mudança"
        elif tem_vi and ai_atual is not None:
            cota_ponto = ai_atual - float(vante_inter)
            cotas_calculadas[p_norm] = cota_ponto
            tipo_leitura = "Vante Intermediária"

        resultados.append({
            'idx': idx,
            'Estação': estacao,
            'Ponto Visado': ponto,
            'Tipo': tipo_leitura,
            'Visada Ré (m)': float(visada_re) if tem_re else None,
            'Vante Inter. (m)': float(vante_inter) if tem_vi else None,
            'Vante Mud. (m)': float(vante_mudanca) if tem_vm else None,
            'AI (m)': float(ai_atual) if ai_atual is not None else None,
            'Cota (m)': float(cota_ponto) if cota_ponto is not None else None
        })

        if cota_ponto is not None:
            pontos_perfil.append({
                'Ponto': ponto,
                'Estação': estacao,
                'Cota': float(cota_ponto)
            })

    df = pd.DataFrame(resultados)
    df_perfil = pd.DataFrame(pontos_perfil)

    if houve_mudanca:
        diff_visadas = soma_re - soma_vante_mudanca
        diff_cotas = cota_ultima_mudanca - float(cota_inicial)
        status_prova = abs(diff_visadas - diff_cotas) < 1e-4
        obs_prova = "Verificação entre estações de mudança (Σ Ré - Σ Vante Mudança = Cota Última Mudança - Cota Inicial)."
    else:
        diff_visadas = soma_re - soma_vante_mudanca
        diff_cotas = 0.0
        status_prova = True
        obs_prova = "Levantamento por estações com visadas intermediárias (sem vantes de mudança)."

    relatorio_prova = {
        'cota_inicial': float(cota_inicial),
        'soma_re': soma_re,
        'soma_vante_mudanca': soma_vante_mudanca,
        'diff_visadas': diff_visadas,
        'diff_cotas': diff_cotas,
        'houve_mudanca': houve_mudanca,
        'status': status_prova,
        'obs': obs_prova,
        'cotas_mapa': cotas_calculadas
    }
    return df, df_perfil, relatorio_prova

def gerar_grafico_perfil_caderneta(df_perfil, cota_plato=None):
    plt.ioff()
    fig, ax = plt.subplots(figsize=(11, 4.8), dpi=100)
    x_indices = np.arange(len(df_perfil))
    cotas = pd.to_numeric(df_perfil['Cota']).values
    rotulos = df_perfil['Ponto'].astype(str).values

    min_c, max_c = float(np.min(cotas)), float(np.max(cotas))
    if cota_plato is not None:
        min_c = min(min_c, float(cota_plato))
        max_c = max(max_c, float(cota_plato))
    margin = (max_c - min_c) * 0.25 if max_c != min_c else 0.5

    ax.plot(x_indices, cotas, marker='o', color='#1F4E78', linewidth=2.2, markersize=5, label='Terreno Natural')
    ax.fill_between(x_indices, cotas, min_c - margin, color='#1F4E78', alpha=0.12)

    if cota_plato is not None:
        ax.axhline(cota_plato, color='#d9534f', linestyle='--', linewidth=1.8, label=f'Cota de Projeto / Platô ({cota_plato:.{casas_decimais_cota}f} m)')

    passo_rotulo = max(1, len(x_indices) // 25)
    for i in range(0, len(x_indices), passo_rotulo):
        ax.annotate(
            f"{cotas[i]:.{casas_decimais_cota}f}",
            (x_indices[i], cotas[i]),
            textcoords="offset points", xytext=(0, 7),
            ha='center', fontsize=7.5, fontweight='bold',
            bbox=dict(boxstyle="round,pad=0.18", fc="white", ec="#1F4E78", lw=0.6, alpha=0.85)
        )

    ax.set_xticks(x_indices)
