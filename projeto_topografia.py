def gerar_planilha_excel(caminho='planilha_caminhamento.xlsx'):
    '''Gera o .xlsx com os dados atuais, na precisão selecionada nos botões ▲▼.'''
    import io
    import datetime
    try:
        import xlsxwriter
    except ImportError:
        import subprocess, sys, importlib
        try:
            subprocess.check_call([sys.executable, '-m', 'pip', 'install', '-q', 'xlsxwriter'])
            importlib.invalidate_caches()
            import xlsxwriter
        except Exception:
            raise RuntimeError("Não consegui instalar a biblioteca 'xlsxwriter'. Rode em uma célula: !pip install xlsxwriter")

    r = ultimo_resultado
    if not r:
        raise ValueError("Nenhum alinhamento cadastrado para exportar.")

    cb, cc = casas_decimais_brutas, casas_decimais_comp
    nb, nc = _fmt_num_excel(cb), _fmt_num_excel(cc)
    nb_ew = f'{nb}" E";{nb}" W";{nb}'# ΔX Bruto: positivo = E | negativo = W
    nb_ns = f'{nb}" N";{nb}" S";{nb}'# ΔY Bruto: positivo = N | negativo = S
    nc_ew = f'{nc}" E";{nc}" W";{nc}'# ΔX Comp.: positivo = E | negativo = W
    nc_ns = f'{nc}" N";{nc}" S";{nc}'# ΔY Comp.: positivo = N | negativo = S

    wb = xlsxwriter.Workbook(caminho)
    ws = wb.add_worksheet('Caminhamento')
    ws.hide_gridlines(2)
    ws.set_landscape(); ws.set_paper(9); ws.fit_to_pages(1, 0)   # A4 paisagem, 1 página de largura

    AZUL, AZUL_CLARO, ZEBRA, BORDA = '#1F4E78', '#E6ECF5', '#F4F6F9', '#DCDFE6'
    base = {'font_name': 'Calibri', 'font_size': 11, 'valign': 'vcenter'}

    def f(**kw):
        d = dict(base); d.update(kw)
        return wb.add_format(d)

    f_titulo = f(bold=True, font_size=18, font_color='#FFFFFF', bg_color=AZUL, align='center')
    f_sub = f(italic=True, font_size=10, font_color='#555555', align='center')
    f_secao = f(bold=True, font_size=13, font_color=AZUL, bottom=2, bottom_color=AZUL)
    f_lbl = f(bold=True, bg_color=AZUL_CLARO, border=1, border_color=BORDA, align='left', indent=1)
    f_cab = f(bold=True, font_color=AZUL, bg_color=AZUL_CLARO, align='center', text_wrap=True,
              top=1, bottom=2, bottom_color=AZUL, top_color=BORDA)
    f_total = f(bold=True, font_color=AZUL, bg_color=AZUL_CLARO, align='center',
                top=2, bottom=2, top_color=AZUL, bottom_color=AZUL)

    def celula(zebra, num=None, bold=False, align='center'):
        d = dict(border=1, border_color=BORDA, align=align, bold=bold)
        if zebra:
            d['bg_color'] = ZEBRA
        if num:
            d['num_format'] = num
        return f(**d)

    def val(num=None, align='left'):
        d = dict(border=1, border_color=BORDA, align=align, bold=True)
        if num:
            d['num_format'] = num
        return f(**d)

    def celula_total(num=None):
        d = dict(bold=True, font_color=AZUL, bg_color=AZUL_CLARO, align='center',
                 top=2, bottom=2, top_color=AZUL, bottom_color=AZUL)
        if num:
            d['num_format'] = num
        return f(**d)

    larguras = [14, 15, 15, 16, 18, 15, 19, 19, 19, 19, 18, 18]
    for i, w in enumerate(larguras):
        ws.set_column(i, i, w)

    # --- Título ---
    ws.set_row(0, 34)
    ws.merge_range('A1:L1', 'RELATÓRIO DE CAMINHAMENTO — CALCULADORA PLANIMÉTRICA', f_titulo)
    ws.merge_range('A2:L2', f"Poligonal {r['tipo'].upper()}  •  Gerado em {datetime.datetime.now():%d/%m/%Y %H:%M}", f_sub)

    # --- Resumo Geral e Fechamento ---
    linha = 3
    ws.merge_range(linha, 0, linha, 11, '1. DADOS GERAIS E FECHAMENTO', f_secao)
    linha += 1

    resumo = [
        ('Estação Inicial — X0 (m)', round(r['x0'], cc), nc),
        ('Estação Inicial — Y0 (m)', round(r['y0'], cc), nc),
        ('Tipo de poligonal', 'Fechada' if r['tipo'] == 'fechada' else 'Aberta', None),
        ('Tipo de ângulo / Sentido', f"{r['tipo_angulo_desc']}  •  {r['sentido_desc']}", None),
        ('Número de alinhamentos', len(r['tabela']), '0'),
        ('Perímetro Total (m)' if r['tipo'] == 'fechada' else 'Extensão Total (m)', round(r['soma_dh'], 6), '0.000000'),
    ]

    if r['area_m2'] is not None:
        resumo += [
            ('Área (m²)', round(r['area_m2'], cc + 2), _fmt_num_excel(cc + 2)),
            ('Área (ha)', round(r['area_m2'] / 10000.0, 6), '0.000000'),
        ]
    else:
        resumo += [('Área', 'N/A (Poligonal Aberta ou menos de 3 alinhamentos)', None)]

    if r['tipo'] == 'fechada':
        resumo += [
            ('Somatório dos Ângulos Lidos', r['soma_ang_lidos_str'], None),
            ('Somatório Angular Teórico', r['soma_teorica_str'], None),
            ('Erro Angular (EA)', r['erro_angular_str'], None),
            ('Tolerância Angular (EAt)', r['tolerancia_angular_str'], None),
            ('Distribuição das Correções Angulares', r['desc_correcao_angular'], None),
            ('Erro Linear em X (ex) (m)', round(r['ex'], cc), nc),
            ('Erro Linear em Y (ey) (m)', round(r['ey'], cc), nc),
            ('Erro Linear Absoluto (EL) (m)', round(r['erro_linear_absoluto'], cc), nc),
            ('Precisão Relativa Alcançada (ELFt)', r['precisao_relativa_str'], None),
            ('Soma |ΔX| (m)  /  Fator fc_x', f"{r['soma_abs_X']:.{cb}f} m  |  fc_x = {r['fc_x']:.11f}", None),
            ('Soma |ΔY| (m)  /  Fator fc_y', f"{r['soma_abs_Y']:.{cb}f} m  |  fc_y = {r['fc_y']:.11f}", None),
        ]
    else:
        resumo += [
            ('Deslocamento Acumulado ΔX (m)', round(r['soma_dx_bruto'], cb), nb),
            ('Deslocamento Acumulado ΔY (m)', round(r['soma_dy_bruto'], cb), nb),
        ]

    for rotulo, valor, num in resumo:
        ws.merge_range(linha, 0, linha, 2, rotulo, f_lbl)
        ws.merge_range(linha, 3, linha, 6, valor, val(num))
        linha += 1

    # --- Tabela Principal do Caminhamento ---
    linha += 1
    ws.merge_range(linha, 0, linha, 11, '2. PLANILHA DE CÁLCULO DO CAMINHAMENTO', f_secao)
    linha += 1
    ws.set_row(linha, 32)
    cabecalhos = [
        'Trecho', 'Ângulo Lido', 'Ângulo Comp.', 'Azimute\nCorrigido', 'Rumo\nCorrigido',
        'DH (m)',
        f'ΔX Bruto (m)\n{cb} dec', f'ΔY Bruto (m)\n{cb} dec',
        f'ΔX Comp. (m)\n{cc} dec', f'ΔY Comp. (m)\n{cc} dec',
        f'Coord. X (m)\n{cc} dec', f'Coord. Y (m)\n{cc} dec'
    ]
    for c, t in enumerate(cabecalhos):
        ws.write(linha, c, t, f_cab)
    linha += 1

    soma_dx_comp = 0.0
    soma_dy_comp = 0.0

    for i, row in enumerate(r['tabela']):
        z = (i % 2 == 1)
        soma_dx_comp += row['ΔX Comp. (m)']
        soma_dy_comp += row['ΔY Comp. (m)']

        ws.write(linha, 0, row['Trecho'], celula(z, bold=True))
        ws.write(linha, 1, row['Ângulo Lido'], celula(z))
        ws.write(linha, 2, row['Ângulo Comp.'], celula(z))
        ws.write(linha, 3, row['Azimute Corrigido'], celula(z))
        ws.write(linha, 4, row['Rumo Corrigido'], celula(z))
        ws.write_number(linha, 5, row['DH (m)'], celula(z, '0.000000'))
        ws.write_number(linha, 6, round(row['ΔX Bruto (m)'], cb), celula(z, nb_ew))
        ws.write_number(linha, 7, round(row['ΔY Bruto (m)'], cb), celula(z, nb_ns))
        ws.write_number(linha, 8, round(row['ΔX Comp. (m)'], cc), celula(z, nc_ew))
        ws.write_number(linha, 9, round(row['ΔY Comp. (m)'], cc), celula(z, nc_ns))
        ws.write_number(linha, 10, round(row['X (m)'], cc), celula(z, nc))
        ws.write_number(linha, 11, round(row['Y (m)'], cc), celula(z, nc))
        linha += 1

    # Linha de Totais / Fechamento
    ws.set_row(linha, 24)
    ws.merge_range(linha, 0, linha, 4, 'TOTAIS / FECHAMENTO', f_total)
    ws.write_number(linha, 5, round(r['soma_dh'], 6), celula_total('0.000000'))
    ws.write_number(linha, 6, round(r['soma_dx_bruto'], cb), celula_total(nb_ew))
    ws.write_number(linha, 7, round(r['soma_dy_bruto'], cb), celula_total(nb_ns))
    ws.write_number(linha, 8, round(soma_dx_comp, cc), celula_total(nc_ew))
    ws.write_number(linha, 9, round(soma_dy_comp, cc), celula_total(nc_ns))
    ws.write_number(linha, 10, round(r['x_final'], cc), celula_total(nc))
    ws.write_number(linha, 11, round(r['y_final'], cc), celula_total(nc))
    linha += 1

