    ws.merge_range(linha, 0, linha, 9, '4. PLANTA PLANIMÉTRICA', f_secao)
    linha += 1
    fig = criar_figura_irradiacao(r['x0'], r['y0'], r['x_pts'], r['y_pts'], r['nomes'], r['tipo'],
                                  titulo='Planta Planimétrica por Irradiação')
    buf = io.BytesIO()
    fig.savefig(buf, format='png', dpi=110, bbox_inches='tight')
    plt.close(fig)
    buf.seek(0)
    ws.insert_image(linha, 0, 'planta.png', {'image_data': buf, 'x_offset': 10, 'y_offset': 6})

    # --- Aba 2: dados de entrada (medições) ---
    ws2 = wb.add_worksheet('Dados de entrada')
    ws2.hide_gridlines(2)
    ws2.set_landscape(); ws2.set_paper(9); ws2.fit_to_pages(1, 0)
    for i, w in enumerate([14, 30, 17, 36, 15, 15, 15, 15, 15, 24]):
        ws2.set_column(i, i, w)
    ws2.set_row(0, 30)
    ws2.merge_range('A1:J1', 'DADOS DE ENTRADA (MEDIÇÕES)', f_titulo)
