                    g = fs - fi
                    dh_val = calcular_dh_fios(fs, fi, v_dec, tipo_ang_v)
                    if dh_val <= 0:
                        print("Atenção: Com esse ângulo vertical a distância horizontal resulta em zero.")
                        return
