    linha += 1
    ws.merge_range(linha, 0, linha, 9, '2. PONTOS IRRADIADOS (COORDENADAS E VISADAS DA ESTAÇÃO CENTRAL)', f_secao)
    linha += 1
    ws.set_row(linha, 32)
