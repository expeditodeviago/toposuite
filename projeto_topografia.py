# --- FUNÇÃO DE GERAÇÃO DA PLANTA GRÁFICA DA POLIGONAL ---
def criar_figura_poligonal(x_coords, y_coords, nomes_vertices, tipo_poligonal='fechada',
                           titulo='Planta Planimétrica da Poligonal'):   # sem emoji: a fonte do gráfico não tem esse símbolo
    '''Cria e devolve a figura da planta (usada na tela e na planilha Excel).'''
    fig, ax = plt.subplots(figsize=(8, 7))

    # Plota os vértices
    ax.scatter(x_coords, y_coords, color='#1F4E78', s=70, zorder=5, label='Vértices')

    # Plota os alinhamentos
    if tipo_poligonal == 'fechada' and len(x_coords) >= 3:
        x_plot = x_coords + [x_coords[0]]
        y_plot = y_coords + [y_coords[0]]
        ax.plot(x_plot, y_plot, color='#1F4E78', linestyle='-', linewidth=2, label='Poligonal Fechada', zorder=3)
        ax.fill(x_plot, y_plot, color='#1F4E78', alpha=0.12)
    else:
        ax.plot(x_coords, y_coords, color='#1F4E78', linestyle='--', linewidth=2, label='Poligonal Aberta', zorder=3)

    # Anotações dos nomes e coordenadas de cada vértice
    for i, nome in enumerate(nomes_vertices):
        ax.annotate(
            f" {nome}\n({x_coords[i]:.{casas_decimais_comp}f}, {y_coords[i]:.{casas_decimais_comp}f})",
            (x_coords[i], y_coords[i]),
            xytext=(6, 6), textcoords='offset points',
            fontsize=9, fontweight='bold', color='#2c3e50',
            bbox=dict(boxstyle="round,pad=0.3", fc="#ffffff", ec="#1F4E78", lw=1, alpha=0.85)
        )

    # Destaca o ponto inicial
    ax.scatter([x_coords[0]], [y_coords[0]], color='#d9534f', s=110, zorder=6,
               label=f'Estação Inicial ({nomes_vertices[0]})')

    ax.set_aspect('equal', adjustable='datalim')
    ax.grid(True, linestyle=':', alpha=0.6)
    ax.set_xlabel('Coordenada X (m)', fontsize=11, fontweight='bold', color='#1F4E78')
    ax.set_ylabel('Coordenada Y (m)', fontsize=11, fontweight='bold', color='#1F4E78')
    ax.set_title(titulo, fontsize=14, fontweight='bold', color='#1F4E78', pad=15)
    ax.legend(loc='upper right', frameon=True, facecolor='#ffffff', edgecolor='#1F4E78')

    plt.tight_layout()
    return fig

def desenhar_grafico_poligonal(x_coords, y_coords, nomes_vertices, tipo_poligonal='fechada'):
    with out_grafico:
        clear_output()
        if not x_coords or len(x_coords) < 2:
            return
        fig = criar_figura_poligonal(x_coords, y_coords, nomes_vertices, tipo_poligonal)
        display(fig)
        plt.close(fig)

