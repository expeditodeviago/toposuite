def parse_optional_float(val):
    """Lê número aceitando vírgula ou ponto. Retorna None se estiver vazio."""
    if val is None:
        return None
    s = str(val).strip().replace(',', '.')
    if not s:
        return None
    try:
        return float(s)
    except ValueError:
        return None


def parse_float(val):
    """Converte entrada para float padrão (0.0 se vazio)."""
    res = parse_optional_float(val)
    return res if res is not None else 0.0


def gms_para_dec(g, m=0, s=0):
    """Converte Graus, Minutos e Segundos para Graus Decimais preservando sinal (inclusive -0)."""
    g_val, m_val, s_val = parse_float(g), parse_float(m), parse_float(s)
    sinal = -1.0 if (g_val < 0 or str(g).strip().startswith('-')) else 1.0
    return sinal * (abs(g_val) + (m_val / 60.0) + (s_val / 3600.0))


def dec_para_gms_tuple(dec_deg, casas_seg=1):
    """Converte graus decimais para tupla (G, M, S) normalizada em [0, 360)."""
    dec_deg = dec_deg % 360.0
    val = abs(dec_deg)
    g = int(val)
    m_full = (val - g) * 60.0
    m = int(m_full)
    s = round((m_full - m) * 60.0, casas_seg)
    if s >= 60.0:
        s = 0.0
        m += 1
    if m >= 60:
        m = 0
        g = (g + 1) % 360
    return g, m, s


def dec_para_gms_str(dec_deg, casas_seg=1):
    """Formata graus decimais como G° MM'SS"."""
    g, m, s = dec_para_gms_tuple(dec_deg, casas_seg)
    if abs(s - round(s)) < 1e-3:
        return f"{g}° {m:02d}'{int(round(s)):02d}\""
    return f"{g}° {m:02d}'{s:04.1f}\""


def dec_para_gms_assinado(dec_deg):
    """Formata ângulos assinados (ex.: depressão vertical ou erro angular negativo)."""
    return ("-" if dec_deg < -1e-9 else "") + dec_para_gms_str(abs(dec_deg))


def campos_gms(dec_deg, casas_seg=1):
    """Decompõe graus decimais em strings (G, M, S) para formulários de edição."""
    neg = dec_deg < 0
    g, m, s = dec_para_gms_tuple(abs(dec_deg), casas_seg)
    return (f"-{g}"if neg else str(g)), str(m), str(s)


def azimute_para_rumo_dms(az_deg):
    az = az_deg % 360.0
    if 0 <= az < 90:
        rumo_val, quad = az, "NE"
    elif 90 <= az < 180:
        rumo_val, quad = 180.0 - az, "SE"
    elif 180 <= az < 270:
        rumo_val, quad = az - 180.0, "SW"
    else:
        rumo_val, quad = 360.0 - az, "NW"
    return f"{dec_para_gms_str(rumo_val)} {quad}"


def area_gauss(x, y):
    n = len(x)
    soma1 = sum(x[i] * y[(i + 1) % n] for i in range(n))
    soma2 = sum(y[i] * x[(i + 1) % n] for i in range(n))
    return abs(soma1 - soma2) / 2.0


def resolver_fios(fs, fm, fi):
    informados = [f for f in [fs, fm, fi] if f > 0]
    if len(informados) == 2:
        if fs > 0 and fi > 0 and fm == 0:
            fm = round((fs + fi) / 2.0, 6)
        elif fs > 0 and fm > 0 and fi == 0:
            fi = round(2.0 * fm - fs, 6)
        elif fm > 0 and fi > 0 and fs == 0:
            fs = round(2.0 * fm - fi, 6)
    elif len(informados) == 3 and fm == 0:
        fm = round((fs + fi) / 2.0, 6)
    return fs, fm, fi


