def fmt_dx(valor, casas):
    """Formata ΔX sem o sinal '-', com sufixo: E (positivo) ou W (negativo)."""
    v = float(f"{valor:.{casas}f}")
    txt = f"{abs(v):.{casas}f}"
    sufixo = " E" if v > 0 else (" W" if v < 0 else "")
    return txt + sufixo

def fmt_dy(valor, casas):
    """Formata ΔY sem o sinal '-', com sufixo: N (positivo) ou S (negativo)."""
    v = float(f"{valor:.{casas}f}")
    txt = f"{abs(v):.{casas}f}"
    sufixo = " N" if v > 0 else (" S" if v < 0 else "")
    return txt + sufixo

def validar_angulo(g, m, s, nome="ângulo"):
    """Valida graus/minutos/segundos digitados. Retorna (valor_decimal, mensagem_de_erro)."""
    campos = [str(g).strip(), str(m).strip(), str(s).strip()]
    if not any(campos):
        return None, f"Informe o {nome} lido (digite 0 se a visada for na própria ré)."
    for c in campos:
        if c and parse_optional_float(c) is None:
            return None, f"Valor inválido no {nome}: '{c}'. Use apenas números."
    if not (0 <= parse_float(m) < 60) or not (0 <= parse_float(s) < 60):
        return None, f"Minutos e segundos do {nome} devem estar entre 0 e 59,999."
    return gms_para_dec(g, m, s), None

def ler_angulo_vertical(g, m, s, tipo):
    """Ângulo vertical é opcional: em branco assume visada horizontal (Z = 90° ou α = 0°)."""
    if not (str(g).strip() or str(m).strip() or str(s).strip()):
        return (90.0 if tipo == 'zenital' else 0.0), None
    return validar_angulo(g, m, s, "ângulo vertical")

def calcular_dh_fios(fs, fi, v_dec, tipo_ang_v):
    """DH estadimétrica: 100 · g · sen²(Z). Com visada horizontal (Z = 90°) vale 100 · g."""
    z = v_dec if tipo_ang_v == 'zenital' else (90.0 - v_dec)
    return 100.0 * (fs - fi) * (math.sin(math.radians(z)) ** 2)

def _ler_coordenada(texto, nome):
    """Lê X0/Y0. Em branco ou inválido usa 1000 e devolve um aviso para o usuário."""
    t = str(texto).strip()
    if not t:
        return 1000.0, f"{nome} não informado: usando 1000 como padrão."
    v = parse_optional_float(t)
    if v is None:
        return 1000.0, f"{nome} inválido ('{t}'): usando 1000 como padrão."
    return v, None

def _segmentos_se_cruzam(p1, p2, p3, p4):
    def orient(a, b, c):
        return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
    return (orient(p1, p2, p3) * orient(p1, p2, p4) < 0) and (orient(p3, p4, p1) * orient(p3, p4, p2) < 0)

def poligono_se_cruza(xs, ys):
    """True se algum lado do polígono cruza outro (sinal de que os pontos foram digitados fora de ordem)."""
    n = len(xs)
    if n < 4:
        return False
    pts = list(zip(xs, ys))
    for i in range(n):
        for j in range(i + 1, n):
            if (i + 1) % n == j or (j + 1) % n == i:
                continue   # lados vizinhos
            if _segmentos_se_cruzam(pts[i], pts[(i + 1) % n], pts[j], pts[(j + 1) % n]):
                return True
    return False

# --- RÉ DE CADA PONTO: id 0 = Norte | id > 0 = outro ponto | id -1 = valor fixo (ponto de referência removido) ---
def _ponto_por_id(pid):
    for p in caderneta_dados:
        if p.get('id') == pid:
            return p
    return None

def _base_re(pt, visitados=None):
    rid = pt.get('re_id', 0)
    if rid == 0:
        return 0.0
    if rid == -1:
        return pt.get('re_az', 0.0)
    if visitados is None:
        visitados = set()
    ref = _ponto_por_id(rid)
    if ref is None or pt['id'] in visitados:
        return pt.get('re_az', 0.0)   # referência sumiu (ou ré circular): usa o último valor conhecido
    visitados.add(pt['id'])
    return (_base_re(ref, visitados) + ref['ang_lido_dec']) % 360.0

def recalcular_azimutes():
    """Recalcula o azimute de todos os pontos. Se um ponto de referência mudar, quem usa ele como ré acompanha."""
    for p in caderneta_dados:
        base = _base_re(p)
        p['re_az'] = base
        p['az_dec'] = (base + p['ang_lido_dec']) % 360.0

def rotulo_re(pt):
    rid = pt.get('re_id', 0)
    if rid == 0:
        return "Norte"
    az_str = dec_para_gms_str(pt.get('re_az', 0.0))
    ref = _ponto_por_id(rid) if rid > 0 else None
    if ref is not None:
        return f"Ponto {ref['ponto']} (Az: {az_str})"
    return f"Ré fixa (Az: {az_str})"

def depende_de(pt, alvo_id):
    """True se a ré de 'pt'leva, direta ou indiretamente, ao ponto de id 'alvo_id'."""
    visto = set()
    atual = pt
    while atual is not None and atual.get('re_id', 0) > 0 and atual['id'] not in visto:
        visto.add(atual['id'])
        if atual['re_id'] == alvo_id:
            return True
        atual = _ponto_por_id(atual['re_id'])
    return False

