def resolver_fios_com_aviso(fs, fm, fi):
    """Calcula o fio faltante a partir dos outros 2 e retorna uma mensagem explicativa."""
    msg = None
    informados = [f for f in [fs, fm, fi] if f > 0]
    if len(informados) == 2:
        if fs > 0 and fi > 0 and fm == 0:
            fm = round((fs + fi) / 2.0, 6)
            msg = f"ℹFio Médio (FM) não digitado. Calculado automaticamente: FM = (FS + FI) / 2 = {fm:.6f} m"
        elif fs > 0 and fm > 0 and fi == 0:
            fi = round(2.0 * fm - fs, 6)
            msg = f"ℹFio Inferior (FI) não digitado. Calculado automaticamente: FI = 2*FM - FS = {fi:.6f} m"
        elif fm > 0 and fi > 0 and fs == 0:
            fs = round(2.0 * fm - fi, 6)
            msg = f"ℹFio Superior (FS) não digitado. Calculado automaticamente: FS = 2*FM - FI = {fs:.6f} m"
    return fs, fm, fi, msg

