def ao_clicar_adicionar(b):
    with out_status:
        clear_output()

        est_nome = txt_est.value.strip() or f"P{len(alinhamentos_dados)+1}"
        vant_nome = txt_vant.value.strip() or f"P{len(alinhamentos_dados)+2}"
        trecho_str = f"{est_nome} → {vant_nome}"

        g_h = txt_ang_g.value.strip()
        m_h = txt_ang_m.value.strip()
        s_h = txt_ang_s.value.strip()
        if not g_h and not m_h and not s_h:
            print("Atenção: Informe o ângulo horizontal lido no vértice.")
            return
        ang_lido_dec = gms_para_dec(g_h, m_h, s_h)

        if dd_modo_dh.value == 'direta':
            dh_val = parse_optional_float(txt_dh.value)
            if dh_val is None or dh_val <= 0:
                print("Atenção: Digite uma Distância Horizontal (DH) válida maior que zero.")
                return
            fs = fm = fi = g = 0.0
            v_dec = 90.0
            tipo_ang_v = 'zenital'
            modo_desc = "Distância Horizontal Direta (DH)"
        else:
            fs_in = parse_float(txt_fs.value)
            fm_in = parse_float(txt_fm.value)
            fi_in = parse_float(txt_fi.value)
            fs, fm, fi = resolver_fios(fs_in, fm_in, fi_in)
            if fs <= 0 or fi <= 0 or fs <= fi:
                print("Atenção: Informe pelo menos 2 fios estadimétricos válidos (FS > FI).")
                return
            g = fs - fi

            g_v = txt_ang_v_g.value.strip()
            m_v = txt_ang_v_m.value.strip()
            s_v = txt_ang_v_s.value.strip()
            tipo_ang_v = dd_tipo_ang_v.value
            if not g_v and not m_v and not s_v:
                v_dec = 90.0 if tipo_ang_v == 'zenital' else 0.0
            else:
                v_dec = gms_para_dec(g_v, m_v, s_v)

            z_dec = v_dec if tipo_ang_v == 'zenital' else (90.0 - v_dec)
            z_rad = math.radians(z_dec)
            dh_val = 100.0 * g * (math.sin(z_rad) ** 2)
            modo_desc = "Fios Estadimétricos (FS, FM, FI)"

        ponto_dado = {
            'estacao': est_nome,
            'vante': vant_nome,
            'trecho': trecho_str,
            'ang_lido_dec': ang_lido_dec,
            'dh': dh_val,
            'fs': fs,
            'fm': fm,
            'fi': fi,
            'g': g,
            'v_dec': v_dec,
            'tipo_ang_v': tipo_ang_v,
            'modo_dh': dd_modo_dh.value,
            'modo_dist_desc': modo_desc
        }

        alinhamentos_dados.append(ponto_dado)
        print(f"Alinhamento '{trecho_str}'adicionado com sucesso! (DH = {dh_val:.6f} m)")

        txt_est.value = vant_nome
        try:
            num = int(''.join(filter(str.isdigit, vant_nome)))
            txt_vant.value = f"P{num+1}"
        except Exception:
            txt_vant.value = f"P{len(alinhamentos_dados)+2}"

        txt_dh.value = ''
        txt_fs.value = ''
        txt_fm.value = ''
        txt_fi.value = ''
        txt_ang_g.value = ''
        txt_ang_m.value = ''
        txt_ang_s.value = ''
        txt_ang_v_g.value = ''
        txt_ang_v_m.value = ''
        txt_ang_v_s.value = ''

    atualizar_tabela_tela()

