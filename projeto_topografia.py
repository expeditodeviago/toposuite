def obter_poligono_contorno(df_malha):
    """Determina o polígono fechado de contorno do terreno (usando os vértices padrão ou ordenação angular)."""
    mapa_pts = {normalize_point_name(r['Ponto']): (float(r['X']), float(r['Y'])) for _, r in df_malha.iterrows()}
    coords_contorno = [mapa_pts[normalize_point_name(nome)] for nome in CONTORNO_TERRENO_PADRAO if normalize_point_name(nome) in mapa_pts]

    if len(coords_contorno) >= 4:
        return np.array(coords_contorno)

    pts = df_malha[['X', 'Y']].drop_duplicates().values
    if len(pts) < 3:
        return None
    cx, cy = np.mean(pts[:, 0]), np.mean(pts[:, 1])
    angulos = np.arctan2(pts[:, 1] - cy, pts[:, 0] - cx)
    return pts[np.argsort(angulos)]

def interpolar_curvas_entre_pontos(cota_a, cota_b, dh_ab, equidistancia=None):
    if equidistancia is None:
        equidistancia = EQUIDISTANCIA_PADRAO
    if cota_a == cota_b or dh_ab <= 0 or equidistancia <= 0:
        return []
    c_min, c_max = min(cota_a, cota_b), max(cota_a, cota_b)
    primeira_cota = math.ceil((c_min + 1e-9) / equidistancia) * equidistancia
    cotas_curvas = np.arange(primeira_cota, c_max - 1e-9, equidistancia)
    pontos_interpolados = []
    for c_curva in cotas_curvas:
        x_dist = dh_ab * (c_curva - cota_a) / (cota_b - cota_a)
        pontos_interpolados.append({
            'Cota da Curva (m)': round(float(c_curva), 3),
            'Distância a partir de A (m)': round(float(x_dist), 3),
            'Distância a partir de B (m)': round(float(dh_ab - x_dist), 3)
        })
    return pontos_interpolados

def _preparar_malha_interpolada(df_malha, equidistancia=None, recortar_contorno=True):
    """Interpola a superfície 3D, aplica suavização e recorta pelo polígono de contorno."""
    if equidistancia is None:
        equidistancia = EQUIDISTANCIA_PADRAO
    x = df_malha['X'].values.astype(float)
    y = df_malha['Y'].values.astype(float)
    z = df_malha['Cota'].values.astype(float)
    nomes = df_malha['Ponto'].astype(str).values

    if len(x) < 3 or len(np.unique(x)) < 2 or len(np.unique(y)) < 2:
        return None

    pad_x = (max(x) - min(x)) * 0.03
    pad_y = (max(y) - min(y)) * 0.03
    xi = np.linspace(min(x) - pad_x, max(x) + pad_x, 200)
    yi = np.linspace(min(y) - pad_y, max(y) + pad_y, 200)
    xi_grid, yi_grid = np.meshgrid(xi, yi)

    zi_linear = griddata((x, y), z, (xi_grid, yi_grid), method='linear')
    nan_mask = np.isnan(zi_linear)
    zi_filled = zi_linear.copy()
    if nan_mask.any():
        zi_filled[nan_mask] = griddata((x, y), z, (xi_grid, yi_grid), method='nearest')[nan_mask]

    zi_smooth = gaussian_filter(zi_filled, sigma=1.1)

    poly_verts = obter_poligono_contorno(df_malha)
    if recortar_contorno and poly_verts is not None and len(poly_verts) >= 3:
        mpl_path = MplPath(poly_verts)
        grid_points = np.column_stack((xi_grid.ravel(), yi_grid.ravel()))
        inside_mask = mpl_path.contains_points(grid_points, radius=0.05).reshape(xi_grid.shape)
        zi_masked = np.where(inside_mask, zi_smooth, np.nan)
    else:
        zi_masked = zi_smooth

    z_min_round = math.floor(np.min(z) / equidistancia) * equidistancia
    z_max_round = math.ceil(np.max(z) / equidistancia) * equidistancia
    niveis = np.arange(z_min_round, z_max_round + equidistancia * 0.5, equidistancia)

    return {
        'x': x, 'y': y, 'z': z, 'nomes': nomes,
        'xi_grid': xi_grid, 'yi_grid': yi_grid, 'zi_masked': zi_masked,
        'poly_verts': poly_verts, 'niveis': niveis, 'equidistancia': equidistancia
    }

